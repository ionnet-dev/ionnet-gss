/**
 * Protocol generator. Reads every `protocol/schema/*.json` and writes
 *   shared/protocol/protocol.gen.ts           TypeScript types, constants and message maps
 *   agent/internal/protocol/protocol_gen.go   Go structs, enums and constants (gofmt'd)
 *
 * Usage:  deno task protocol            write both files
 *         deno task protocol --check    exit 1 when the committed files are stale
 *
 * Supported JSON Schema subset (anything else is an error, so the two outputs can't silently differ):
 *   $defs                named types: objects with `properties`, string enums, or aliases of the forms below
 *   type                 string | integer | number | boolean | array | object | [T, "null"] | [T1, T2] (union)
 *   format: date-time    string in TS, time.Time in Go
 *   enum (strings)       union in TS, a named string type + consts in Go (inline enums become plain strings in Go)
 *   items                arrays
 *   additionalProperties (schema) on an object without `properties`: a map with string keys
 *   $ref                 "#/$defs/Name" or "other.json#/$defs/Name"; def names are global across files
 *   oneOf [ $ref, {type: "null"} ]   nullable reference
 *   {} / no type         unknown in TS, json.RawMessage in Go
 *   description          JSDoc / Go comments
 * Inline objects with `properties` are refused: name them in `$defs`.
 * Ignored (documentation and future validation only): pattern, format other than date-time, min/maxProperties, $id.
 *
 * Custom keywords (top level of a schema file):
 *   x-channels   { name: { description, parties: { party: "MapPrefix" }, goPrefix } }   (envelope.json only)
 *   x-constants  { UPPER_SNAKE: { value: number | string, description } }
 *   x-messages   [ { channel, type, kind: "request" | "event", from, milestone, request?, response?, data?, description } ]
 */
import Path from "node:path";
import { fileURLToPath } from "node:url";

//#region Schema model
interface Schema {
  type?: string | string[];
  description?: string;
  properties?: Record<string, Schema>;
  required?: string[];
  additionalProperties?: boolean | Schema;
  items?: Schema;
  enum?: string[];
  const?: string;
  $ref?: string;
  format?: string;
  oneOf?: Schema[];
}

interface ChannelDecl {
  description: string;
  parties: Record<string, string>;
  goPrefix: string;
}

interface ConstantDecl {
  value: number | string;
  description: string;
}

interface MessageDecl {
  channel: string;
  type: string;
  kind: "request" | "event";
  from: string;
  milestone: number;
  request?: string;
  response?: string;
  data?: string;
  description: string;
}

interface SchemaFile {
  $id?: string;
  title?: string;
  description?: string;
  $defs?: Record<string, Schema>;
  "x-channels"?: Record<string, ChannelDecl>;
  "x-constants"?: Record<string, ConstantDecl>;
  "x-messages"?: MessageDecl[];
}

type TypeRef =
  | { k: "named"; name: string }
  | { k: "string"; values?: string[] }
  | { k: "datetime" }
  | { k: "integer" }
  | { k: "number" }
  | { k: "boolean" }
  | { k: "any" }
  | { k: "array"; of: TypeRef }
  | { k: "map"; of: TypeRef }
  | { k: "nullable"; of: TypeRef }
  | { k: "union"; of: TypeRef[] };

interface Field {
  name: string;
  type: TypeRef;
  optional: boolean;
  description?: string;
}

type Def =
  | { kind: "struct"; name: string; file: string; description?: string; fields: Field[] }
  | { kind: "enum"; name: string; file: string; description?: string; values: string[] }
  | { kind: "alias"; name: string; file: string; description?: string; type: TypeRef };
//#endregion

const ROOT = Path.resolve(Path.dirname(fileURLToPath(import.meta.url)), "..");
const SCHEMA_DIR = Path.join(ROOT, "protocol", "schema");
const TS_OUT = Path.join(ROOT, "shared", "protocol", "protocol.gen.ts");
const GO_OUT = Path.join(ROOT, "agent", "internal", "protocol", "protocol_gen.go");
const HEADER = "Code generated by `deno task protocol` from protocol/schema/*.json. DO NOT EDIT.";

/**
 * Go initialisms, so `serverId` becomes `ServerID` and `memoryMb` becomes `MemoryMB`.
 */
const INITIALISMS = new Set(["id", "url", "cpu", "os", "api", "uuid", "json", "ip", "mb", "uid", "gid", "tcp", "udp", "pid", "ttl", "sha"]);

//#region Loading
async function loadFiles(): Promise<Map<string, SchemaFile>> {
  const names: string[] = [];
  for await (const entry of Deno.readDir(SCHEMA_DIR)) {
    if (entry.isFile && entry.name.endsWith(".json")) names.push(entry.name);
  }
  // envelope.json first (channels, the frame), then the rest alphabetically for a stable output.
  names.sort((a, b) => (a === "envelope.json" ? -1 : b === "envelope.json" ? 1 : a.localeCompare(b)));
  const files = new Map<string, SchemaFile>();
  for (const name of names) {
    files.set(name, JSON.parse(await Deno.readTextFile(Path.join(SCHEMA_DIR, name))) as SchemaFile);
  }
  return files;
}

function refName(ref: string, file: string, defNames: Set<string>): string {
  const match = /^(?:([\w.-]+\.json))?#\/\$defs\/(\w+)$/.exec(ref);
  if (!match) throw new Error(`${file}: unsupported $ref "${ref}". Use "#/$defs/Name" or "other.json#/$defs/Name".`);
  const name = match[2];
  if (!defNames.has(name)) throw new Error(`${file}: $ref "${ref}" points at an unknown definition "${name}".`);
  return name;
}

function toTypeRef(schema: Schema, where: string, defNames: Set<string>): TypeRef {
  if (schema.$ref) return { k: "named", name: refName(schema.$ref, where, defNames) };
  if (schema.oneOf) {
    const nonNull = schema.oneOf.filter((s) => s.type !== "null");
    if (nonNull.length !== 1 || schema.oneOf.length !== 2) {
      throw new Error(`${where}: oneOf is only supported as [ <schema>, { "type": "null" } ].`);
    }
    return { k: "nullable", of: toTypeRef(nonNull[0], where, defNames) };
  }
  if (Array.isArray(schema.type)) {
    const types = schema.type.filter((t) => t !== "null");
    const inner = types.length === 1
      ? toTypeRef({ ...schema, type: types[0] }, where, defNames)
      : { k: "union" as const, of: types.map((t) => toTypeRef({ type: t }, where, defNames)) };
    return types.length === schema.type.length ? inner : { k: "nullable", of: inner };
  }
  switch (schema.type) {
    case undefined:
      return { k: "any" };
    case "string":
      if (schema.format === "date-time") return { k: "datetime" };
      if (schema.const !== undefined) return { k: "string", values: [schema.const] };
      return { k: "string", values: schema.enum };
    case "integer":
      return { k: "integer" };
    case "number":
      return { k: "number" };
    case "boolean":
      return { k: "boolean" };
    case "array":
      if (!schema.items) throw new Error(`${where}: arrays need "items".`);
      return { k: "array", of: toTypeRef(schema.items, `${where}[]`, defNames) };
    case "object":
      if (schema.properties) {
        throw new Error(`${where}: inline objects with "properties" are not supported. Move it to $defs and $ref it.`);
      }
      if (typeof schema.additionalProperties === "object") {
        return { k: "map", of: toTypeRef(schema.additionalProperties, `${where}{}`, defNames) };
      }
      return { k: "map", of: { k: "any" } };
    default:
      throw new Error(`${where}: unsupported type "${schema.type}".`);
  }
}

function collect(files: Map<string, SchemaFile>) {
  const defNames = new Set<string>();
  for (const [file, content] of files) {
    for (const name of Object.keys(content.$defs ?? {})) {
      if (defNames.has(name)) throw new Error(`${file}: definition "${name}" is already defined in another file. Names are global.`);
      defNames.add(name);
    }
  }

  const defs: Def[] = [];
  const channels: Record<string, ChannelDecl> = {};
  const constants: [string, ConstantDecl][] = [];
  const messages: MessageDecl[] = [];

  for (const [file, content] of files) {
    Object.assign(channels, content["x-channels"] ?? {});
    for (const entry of Object.entries(content["x-constants"] ?? {})) constants.push(entry);
    messages.push(...(content["x-messages"] ?? []));

    for (const [name, schema] of Object.entries(content.$defs ?? {})) {
      const where = `${file}#/$defs/${name}`;
      if (schema.type === "object" && schema.properties) {
        const required = new Set(schema.required ?? []);
        for (const key of required) {
          if (!(key in schema.properties)) throw new Error(`${where}: required property "${key}" is not in "properties".`);
        }
        const fields = Object.entries(schema.properties).map(([key, prop]): Field => ({
          name: key,
          type: toTypeRef(prop, `${where}.${key}`, defNames),
          optional: !required.has(key),
          description: prop.description,
        }));
        defs.push({ kind: "struct", name, file, description: schema.description, fields });
      }
      else if (schema.type === "string" && schema.enum) {
        defs.push({ kind: "enum", name, file, description: schema.description, values: schema.enum });
      }
      else {
        defs.push({ kind: "alias", name, file, description: schema.description, type: toTypeRef(schema, where, defNames) });
      }
    }
  }

  const seen = new Set<string>();
  for (const m of messages) {
    const where = `message "${m.type}" (${m.channel})`;
    const channel = channels[m.channel];
    if (!channel) throw new Error(`${where}: unknown channel. Declare it in envelope.json x-channels.`);
    if (!(m.from in channel.parties)) throw new Error(`${where}: "from" must be one of ${Object.keys(channel.parties).join(", ")}.`);
    if (seen.has(`${m.channel}:${m.type}`)) throw new Error(`${where}: declared twice.`);
    seen.add(`${m.channel}:${m.type}`);
    const refs = m.kind === "request" ? [m.request, m.response] : [m.data];
    for (const ref of refs) {
      if (!ref || !defNames.has(ref)) throw new Error(`${where}: payload type "${ref}" is missing or not a known definition.`);
    }
  }

  return { defs, channels, constants, messages };
}
//#endregion

//#region Naming
function splitWords(name: string): string[] {
  return name
    .split(/[-_.\s]+/)
    .flatMap((part) => part.replace(/([a-z0-9])([A-Z])/g, "$1 $2").split(" "))
    .filter(Boolean);
}

function goName(name: string): string {
  return splitWords(name)
    .map((w) => {
      const lower = w.toLowerCase();
      if (INITIALISMS.has(lower)) return lower.toUpperCase();
      return lower[0].toUpperCase() + lower.slice(1);
    })
    .join("");
}

function tsKey(name: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
}
//#endregion

//#region TypeScript
function tsType(t: TypeRef): string {
  switch (t.k) {
    case "named": return t.name;
    case "string": return t.values ? t.values.map((v) => JSON.stringify(v)).join(" | ") : "string";
    case "datetime": return "string";
    case "integer":
    case "number": return "number";
    case "boolean": return "boolean";
    case "any": return "unknown";
    case "array": {
      const inner = tsType(t.of);
      return /[| ]/.test(inner) ? `(${inner})[]` : `${inner}[]`;
    }
    case "map": return `Record<string, ${tsType(t.of)}>`;
    case "nullable": return `${tsType(t.of)} | null`;
    case "union": return t.of.map(tsType).join(" | ");
  }
}

function tsDoc(text: string | undefined, indent = ""): string {
  if (!text) return "";
  return `${indent}/**\n${text.split("\n").map((l) => `${indent} * ${l}`).join("\n")}\n${indent} */\n`;
}

function renderTs(model: ReturnType<typeof collect>): string {
  const out: string[] = [`// ${HEADER}\n`];

  out.push("//#region Constants");
  for (const [name, c] of model.constants) {
    out.push(`${tsDoc(c.description)}export const ${name} = ${JSON.stringify(c.value)};\n`);
  }
  out.push("//#endregion\n");

  let file = "";
  for (const def of model.defs) {
    if (def.file !== file) {
      if (file) out.push("//#endregion\n");
      file = def.file;
      out.push(`//#region ${file}`);
    }
    const doc = tsDoc(def.description);
    if (def.kind === "struct") {
      if (def.fields.length === 0) {
        out.push(`${doc}export type ${def.name} = Record<string, never>;\n`);
        continue;
      }
      const fields = def.fields.map((f) => `${tsDoc(f.description, "  ")}  ${tsKey(f.name)}${f.optional ? "?" : ""}: ${tsType(f.type)};`);
      out.push(`${doc}export interface ${def.name} {\n${fields.join("\n")}\n}\n`);
    }
    else if (def.kind === "enum") {
      out.push(`${doc}export type ${def.name} = ${def.values.map((v) => JSON.stringify(v)).join(" | ")};`);
      out.push(`export const ${def.name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase()}_VALUES: readonly ${def.name}[] = [${def.values.map((v) => JSON.stringify(v)).join(", ")}];\n`);
    }
    else {
      out.push(`${doc}export type ${def.name} = ${tsType(def.type)};\n`);
    }
  }
  if (file) out.push("//#endregion\n");

  out.push("//#region Messages");
  out.push(`/**\n * One message type of a channel.\n */\nexport interface MessageSpec {\n  channel: ${Object.keys(model.channels).map((c) => JSON.stringify(c)).join(" | ")};\n  type: string;\n  kind: "request" | "event";\n  from: string;\n  milestone: number;\n}\n`);
  for (const [channelName, channel] of Object.entries(model.channels)) {
    for (const [party, prefix] of Object.entries(channel.parties)) {
      for (const kind of ["request", "event"] as const) {
        const list = model.messages.filter((m) => m.channel === channelName && m.from === party && m.kind === kind);
        const mapName = `${prefix}${kind === "request" ? "Requests" : "Events"}`;
        const doc = tsDoc(`${kind === "request" ? "Requests" : "Events"} \`${party}\` sends on the \`${channelName}\` channel. ${channel.description}`);
        if (list.length === 0) {
          out.push(`${doc}export type ${mapName} = Record<never, never>;\n`);
          continue;
        }
        const entries = list.map((m) => {
          const type = kind === "request" ? `{ request: ${m.request}; response: ${m.response} }` : m.data;
          return `${tsDoc(`${m.description} (M${m.milestone})`, "  ")}  ${JSON.stringify(m.type)}: ${type};`;
        });
        out.push(`${doc}export interface ${mapName} {\n${entries.join("\n")}\n}\n`);
      }
    }
  }
  const specs = model.messages.map((m) =>
    `  { channel: ${JSON.stringify(m.channel)}, type: ${JSON.stringify(m.type)}, kind: ${JSON.stringify(m.kind)}, from: ${JSON.stringify(m.from)}, milestone: ${m.milestone} },`
  );
  out.push(`/**\n * Every message type, in schema order.\n */\nexport const MESSAGES: readonly MessageSpec[] = [\n${specs.join("\n")}\n];`);
  out.push("//#endregion\n");
  return out.join("\n");
}
//#endregion

//#region Go
function goType(t: TypeRef, defs: Map<string, Def>): string {
  switch (t.k) {
    case "named": return t.name;
    case "string": return "string";
    case "datetime": return "time.Time";
    case "integer": return "int64";
    case "number": return "float64";
    case "boolean": return "bool";
    case "any": return "json.RawMessage";
    case "array": return `[]${goType(t.of, defs)}`;
    case "map": return `map[string]${goType(t.of, defs)}`;
    case "nullable": {
      const inner = goType(t.of, defs);
      return isNilable(t.of) ? inner : `*${inner}`;
    }
    case "union": return "any";
  }
}

function isNilable(t: TypeRef): boolean {
  return t.k === "array" || t.k === "map" || t.k === "any" || t.k === "union";
}

function isStruct(t: TypeRef, defs: Map<string, Def>): boolean {
  if (t.k === "datetime") return true;
  return t.k === "named" && defs.get(t.name)?.kind === "struct";
}

function goComment(name: string, text: string | undefined, indent = ""): string {
  if (!text) return "";
  const body = text.replace(/`/g, "");
  // "Seconds the panel…" reads as "HelloTimeoutSec seconds the panel…"; keep words like "WebSocket" or "SHA-256" as is.
  const lead = (l: string) => /^[A-Z][a-z]+\b/.test(l) && !/^[A-Z][a-z]+[A-Z]/.test(l) ? l[0].toLowerCase() + l.slice(1) : l;
  return body.split("\n").map((l, i) => `${indent}// ${i === 0 ? `${name} ${lead(l)}` : l}`).join("\n") + "\n";
}

function renderGo(model: ReturnType<typeof collect>): string {
  const defs = new Map(model.defs.map((d) => [d.name, d]));
  const body: string[] = [];

  body.push("const (");
  for (const [name, c] of model.constants) {
    body.push(goComment(goName(name), c.description, "\t") + `\t${goName(name)} = ${JSON.stringify(c.value)}`);
  }
  body.push(")\n");

  for (const def of model.defs) {
    const doc = goComment(def.name, def.description) || `// ${def.name} is defined in protocol/schema/${def.file}.\n`;
    if (def.kind === "struct") {
      const fields = def.fields.map((f) => {
        let type = goType(f.type, defs);
        if (f.optional && isStruct(f.type, defs)) type = `*${type}`;
        const tag = `\`json:"${f.name}${f.optional ? ",omitempty" : ""}"\``;
        return `${goComment(goName(f.name), f.description, "\t")}\t${goName(f.name)} ${type} ${tag}`;
      });
      body.push(`${doc}type ${def.name} struct {\n${fields.join("\n")}\n}\n`);
    }
    else if (def.kind === "enum") {
      body.push(`${doc}type ${def.name} string\n`);
      body.push(`// ${def.name} values.\nconst (\n${def.values.map((v) => `\t${def.name}${goName(v)} ${def.name} = ${JSON.stringify(v)}`).join("\n")}\n)\n`);
    }
    else {
      body.push(`${doc}type ${def.name} = ${goType(def.type, defs)}\n`);
    }
  }

  body.push("// Message types.\nconst (");
  for (const m of model.messages) {
    const channel = model.channels[m.channel];
    const name = `${channel.goPrefix}${goName(m.type)}`;
    const payload = m.kind === "request" ? `request ${m.request}, response ${m.response}` : `event ${m.data}`;
    body.push(`\t// ${name}: ${m.from} → ${m.channel === "agent" ? (m.from === "agent" ? "panel" : "agent") : (m.from === "agent" ? "supervisor" : "agent")}, ${payload} (M${m.milestone}).\n\t${name} = ${JSON.stringify(m.type)}`);
  }
  body.push(")\n");

  body.push(`// MessageSpec describes one message type of a channel.
type MessageSpec struct {
\tChannel   string
\tType      string
\tKind      MessageKind
\tFrom      string
\tMilestone int
}

// Messages lists every message type, in schema order.
var Messages = []MessageSpec{`);
  for (const m of model.messages) {
    body.push(`\t{Channel: ${JSON.stringify(m.channel)}, Type: ${JSON.stringify(m.type)}, Kind: MessageKind${goName(m.kind)}, From: ${JSON.stringify(m.from)}, Milestone: ${m.milestone}},`);
  }
  body.push("}\n");

  const text = body.join("\n");
  const imports = [text.includes("json.RawMessage") ? `"encoding/json"` : "", text.includes("time.Time") ? `"time"` : ""].filter(Boolean);
  const importBlock = imports.length ? `import (\n${imports.map((i) => `\t${i}`).join("\n")}\n)\n\n` : "";
  return `// ${HEADER}\n\n// Package protocol holds the panel↔agent and agent↔supervisor message types.\npackage protocol\n\n${importBlock}${text}`;
}

async function gofmt(source: string): Promise<string> {
  const child = new Deno.Command("gofmt", { stdin: "piped", stdout: "piped", stderr: "piped" }).spawn();
  const writer = child.stdin.getWriter();
  await writer.write(new TextEncoder().encode(source));
  await writer.close();
  const { code, stdout, stderr } = await child.output();
  if (code !== 0) {
    throw new Error(`gofmt rejected the generated Go source:\n${new TextDecoder().decode(stderr)}`);
  }
  return new TextDecoder().decode(stdout);
}
//#endregion

async function main() {
  const check = Deno.args.includes("--check");
  const model = collect(await loadFiles());
  const outputs: [string, string][] = [
    [TS_OUT, renderTs(model)],
    [GO_OUT, await gofmt(renderGo(model))],
  ];

  if (check) {
    const stale: string[] = [];
    for (const [path, content] of outputs) {
      const current = await Deno.readTextFile(path).catch(() => null);
      if (current !== content) stale.push(Path.relative(ROOT, path));
    }
    if (stale.length) {
      console.error(`Generated protocol files are stale: ${stale.join(", ")}. Run \`deno task protocol\` and commit the result.`);
      Deno.exit(1);
    }
    console.log("protocol: generated files are up to date");
    return;
  }

  for (const [path, content] of outputs) {
    await Deno.mkdir(Path.dirname(path), { recursive: true });
    await Deno.writeTextFile(path, content);
    console.log(`wrote ${Path.relative(ROOT, path)}`);
  }
  console.log(`protocol: ${model.defs.length} types, ${model.messages.length} messages, ${model.constants.length} constants`);
}

if (import.meta.main) {
  await main();
}
